// Bundles drizzle/*.sql into a TS module so the app can run migrations without Metro .sql support.
import { readFileSync, writeFileSync } from 'node:fs';

const journal = JSON.parse(readFileSync('drizzle/meta/_journal.json', 'utf8'));
const migrations = {};
for (const entry of journal.entries) {
  migrations[`m${String(entry.idx).padStart(4, '0')}`] = readFileSync(`drizzle/${entry.tag}.sql`, 'utf8');
}
const out = `// GENERATED by scripts/embed-migrations.mjs — do not edit. Run \`npm run db:embed\`.
export default ${JSON.stringify({ journal, migrations }, null, 2)};
`;
writeFileSync('src/data/db/migrations.generated.ts', out);
console.log(`Embedded ${journal.entries.length} migrations`);
